#!/usr/bin/env python3
"""Download Chinese web fonts from Google Fonts once and serve them from this site (run by hand, rarely).

    python3 scripts/fetch-google-fonts.py

Google Fonts already cuts big Chinese fonts into ~100 small woff2 slices, each with a
unicode-range, so the browser loads only the slices holding characters on the page. This script
saves those slices to assets/fonts/ and writes assets/fonts/fonts-google.css, so no request
goes to Google (Datenschutz). All of them are under the SIL OFL; the licences are in
assets/fonts/LICENSES/. The other fonts (Minipax, LTC Round) come from scripts/build-fonts.py."""
import glob, os, re, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "fonts")
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"
# (CSS family, Google Fonts family, file prefix)
FAMILIES = [
    ("Iansui", "Iansui", "iansui"),
]


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60).read()


def main():
    rules = ["/* Generated by scripts/fetch-google-fonts.py. Fonts and licences: assets/fonts/LICENSES/ */"]
    for family, gf, prefix in FAMILIES:
        for old in glob.glob(os.path.join(OUT, prefix + "-[0-9]*.woff2")):
            os.remove(old)
        css = get("https://fonts.googleapis.com/css2?family=%s&display=swap" % gf).decode()
        faces = re.findall(r"@font-face\s*{(.*?)}", css, re.S)
        for i, face in enumerate(faces):
            src = re.search(r"url\((https://[^)]+\.woff2)\)", face).group(1)
            rng = re.search(r"unicode-range:\s*([^;]+);", face)
            weight = re.search(r"font-weight:\s*(\d+)", face).group(1)
            name = "%s-%03d.woff2" % (prefix, i)
            with open(os.path.join(OUT, name), "wb") as f:
                f.write(get(src))
            rules.append('@font-face { font-family: "%s"; font-weight: %s; font-style: normal; font-display: swap; '
                         'src: url("%s") format("woff2");%s }'
                         % (family, weight, name, " unicode-range: %s;" % rng.group(1).strip() if rng else ""))
        print(family, len(faces), "slices")
    keep = tuple(prefix + "-" for _, _, prefix in FAMILIES)  # slices of fonts no longer listed go
    for old in glob.glob(os.path.join(OUT, "*-[0-9][0-9][0-9].woff2")):
        if not os.path.basename(old).startswith(keep):
            os.remove(old)
    with open(os.path.join(OUT, "fonts-google.css"), "w", encoding="utf-8") as f:
        f.write("\n".join(rules) + "\n")


if __name__ == "__main__":
    main()
